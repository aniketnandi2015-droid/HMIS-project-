/**
 * Convenience helper to inject the complete 48h sales demo dataset into LocalStorage
 */
export function injectSalesPitchDemoData(): void {
  // Prepend sales pitch transactions onto existing history
  const currentTxs = LocalStorageAdapter.getTransactions();
  const existingIds = new Set(currentTxs.map((t) => t.id));
  const newTxs = salesPitchTransactions.filter((t) => !existingIds.has(t.id));
  LocalStorageAdapter.saveTransactions([...newTxs, ...currentTxs]);

  // Set discrepancies
  LocalStorageAdapter.saveDiscrepancies(salesPitchDiscrepancies);

  // Set unmet demands
  LocalStorageAdapter.saveUnmetDemands(salesPitchUnmetDemands);

  // Set purchase orders
  LocalStorageAdapter.savePurchaseOrders(salesPitchPurchaseOrders);

  // Set supplier events
  LocalStorageAdapter.saveSupplierEvents(salesPitchSupplierEvents);
}
